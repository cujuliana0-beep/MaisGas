export function readStored<T>(key:string,fallback:T):T { const raw=localStorage.getItem(`maisgas:${key}`); if(!raw) return fallback; // Local storage values are generated by this application.
 const valid = raw.trim().startsWith('{') || raw.trim().startsWith('[') || raw==='null' || raw==='true' || raw==='false' || raw.startsWith('"');
 return valid ? JSON.parse(raw) as T : fallback;
}
export function writeStored<T>(key:string,value:T) { localStorage.setItem(`maisgas:${key}`,JSON.stringify(value)); }
